/**
 * Vendor DealerIQ typefaces once, as base64 `@font-face` rules.
 *
 * Inter (UI) + JetBrains Mono (data) match the brand kit tokens.
 * The reader must run from `file://` with the network off, so we fetch the
 * woff2 files once and emit `src/generated/fonts.css` with bytes inlined.
 */
import { mkdirSync, writeFileSync, existsSync, readFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(HERE, "../src/generated/fonts.css");

const UA =
  "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) " +
  "Chrome/126.0.0.0 Safari/537.36";

const CSS_URL =
  "https://fonts.googleapis.com/css2" +
  "?family=Inter:wght@400;500;600;700;800" +
  "&family=JetBrains+Mono:wght@400;500" +
  "&display=swap";

const STUB = `/* Fonts unavailable at build time - falling back to system stacks.
   Re-run \`npm run fonts\` with a network connection to vendor them. */
`;

const MARKER = "Inter + JetBrains Mono";

function latinBlocks(css: string): string[] {
  const out: string[] = [];
  const re = /\/\*\s*([a-z0-9-]+)\s*\*\/\s*(@font-face\s*\{[^}]*\})/gi;
  for (const m of css.matchAll(re)) {
    if (m[1] === "latin") out.push(m[2]);
  }
  return out;
}

async function main(): Promise<void> {
  mkdirSync(dirname(OUT), { recursive: true });

  if (
    existsSync(OUT) &&
    readFileSync(OUT, "utf8").includes("@font-face") &&
    readFileSync(OUT, "utf8").includes(MARKER)
  ) {
    console.log("fonts · already vendored, skipping");
    return;
  }

  try {
    const res = await fetch(CSS_URL, { headers: { "User-Agent": UA } });
    if (!res.ok) throw new Error(`css ${res.status}`);
    const css = await res.text();

    const blocks = latinBlocks(css);
    if (blocks.length === 0) throw new Error("no latin subset in response");

    let bytes = 0;
    const rendered: string[] = [];

    for (const block of blocks) {
      const urlMatch = /url\((https:\/\/[^)]+\.woff2)\)/.exec(block);
      if (!urlMatch) continue;
      const fontRes = await fetch(urlMatch[1], {
        headers: { "User-Agent": UA },
      });
      if (!fontRes.ok) throw new Error(`woff2 ${fontRes.status}`);
      const buf = Buffer.from(await fontRes.arrayBuffer());
      bytes += buf.byteLength;
      const dataUri = `data:font/woff2;base64,${buf.toString("base64")}`;
      rendered.push(block.replace(urlMatch[0], `url(${dataUri})`));
    }

    if (rendered.length === 0) throw new Error("no woff2 urls found");

    writeFileSync(
      OUT,
      `/* Generated by scripts/fetch-fonts.ts - do not edit.
   ${MARKER}, latin subset, inlined as data URIs so the
   reader needs no network at read time. */\n\n${rendered.join("\n\n")}\n`,
      "utf8",
    );
    const kb = Math.round(bytes / 1024);
    console.log(`fonts · vendored ${rendered.length} faces (${kb} KB woff2)`);
  } catch (err) {
    writeFileSync(OUT, STUB, "utf8");
    const why = err instanceof Error ? err.message : String(err);
    console.warn(`fonts · unavailable (${why}) — using system stacks`);
  }
}

void main();
